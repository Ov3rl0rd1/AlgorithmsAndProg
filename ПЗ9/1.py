#Задача № 1
#1.	Создайте список х: 5, 3, 6, 8, 3, 4, 6, 2, 1, 4, 5, 6, 7, 7.
#2.	Создайте список у: 12, 1, 6, 7, 3, 22, 6, 2, 17, 4, 5, 67, 3, 9.
#3.	Удалите из списка х повторяющиеся элементы.
#4.	Преобразуйте списки во множества.
#5.	Определите число элементов множества у.
#6.	Проверьте, входит ли во множество х следующие элементы: 5, 8, 12, 9.
#7.	Добавьте 9 во множество х.
#8.	Удалить из множества х элементы 8 и 12 (разными способами).
#9.	Объедините множества х и y так, чтобы было создано новое множество w.
#10.	Определите общие элементы множеств х и у.
#11.	Найдите элементы множества х, которые не входят во множество у.
#12.	Найдите элементы, которые входят в х или у, но не в оба множества одновременно.
#13.	Проверьте, является ли х подмножеством w.
#14.	Проверьте, является ли y подмножеством х.
#15.	Проверьте, равны ли множества х и у.
#16.	Определите, х больше у или нет.
#17.	Заморозьте множество х (с помощью метода frozenset()) и попробуйте добавить значение 19 в новое замороженное множество.

# 1-2. Создание списков
x = [5, 3, 6, 8, 3, 4, 6, 2, 1, 4, 5, 6, 7, 7]
y = [12, 1, 6, 7, 3, 22, 6, 2, 17, 4, 5, 67, 3, 9]

print("Список x:", x)
print("Список y:", y)
print()

# 3. Удаление повторяющихся элементов из списка x
x = list(dict.fromkeys(x))
print("Список x без дубликатов:", x)
print()

# 4. Преобразование списков во множества
x_set = set(x)
y_set = set(y)
print("Множество x:", x_set)
print("Множество y:", y_set)
print()

# 5. Определение числа элементов множества y
y_count = len(y_set)
print(f"Количество элементов в множестве y: {y_count}")
print()

# 6. Проверка принадлежности элементов во множество x
elements_to_check = [5, 8, 12, 9]
print("Проверка принадлежности элементов множеству x:")
for element in elements_to_check:
    print(f"  {element} в множестве x: {element in x_set}")
print()

# 7. Добавление 9 во множество x
x_set.add(9)
print("Множество x после добавления 9:", x_set)
print()

# 8. Удаление элементов 8 и 12 из множества x (разные способы)
# Способ 1: remove() - вызывает ошибку если элемента нет
if 8 in x_set:
    x_set.remove(8)
    print("Элемент 8 удален с помощью remove()")

# Способ 2: discard() - не вызывает ошибку если элемента нет
x_set.discard(12)
print("Элемент 12 удален с помощью discard()")
print("Множество x после удаления 8 и 12:", x_set)
print()

# 9. Объединение множеств x и y в новое множество w
w = x_set.union(y_set)
print("Объединение множеств x и y (множество w):", w)
print()

# 10. Определение общих элементов множеств x и y
common_elements = x_set.intersection(y_set)
print("Общие элементы множеств x и y:", common_elements)
print()

# 11. Элементы множества x, которые не входят во множество y
difference = x_set.difference(y_set)
print("Элементы в x, но не в y:", difference)
print()

# 12. Элементы, которые входят в x или y, но не в оба одновременно (симметрическая разность)
symmetric_diff = x_set.symmetric_difference(y_set)
print("Элементы в x или y, но не в оба:", symmetric_diff)
print()

# 13. Проверка, является ли x подмножеством w
is_subset = x_set.issubset(w)
print(f"Является ли x подмножеством w: {is_subset}")
print()

# 14. Проверка, является ли y подмножеством x
is_y_subset_x = y_set.issubset(x_set)
print(f"Является ли y подмножеством x: {is_y_subset_x}")
print()

# 15. Проверка, равны ли множества x и y
are_equal = x_set == y_set
print(f"Равны ли множества x и y: {are_equal}")
print()

# 16. Определение, больше ли x чем y
is_x_greater = x_set > y_set
print(f"Является ли x строгим надмножеством y: {is_x_greater}")
print(f"Размер x: {len(x_set)}, размер y: {len(y_set)}")
print()

# 17. Замораживание множества x и попытка добавления 19
frozen_x = frozenset(x_set)
print("Замороженное множество x:", frozen_x)
print("Попытка добавления 19 в замороженное множество x:")
try:
    frozen_x.add(19)
except AttributeError as e:
    print(f"  Ошибка: {e}")
    print("  frozen_x объект не поддерживает метод add()")
print()

